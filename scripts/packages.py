#!/usr/bin/env python3
"""packages.py - split rc2.dll's reconstruction into work packages of contiguous .text.

From reference/files-rc2.tsv (each function's source file by link order) and the
byte-for-byte matches (names-rc2.tsv): walks the files in .text order and cuts a new
package whenever the current one holds about 1/N of the RC2 code. A package owns its SDK files
(their changed functions) and the runs of RC2's own code between them, so every function
belongs to exactly one package. The C runtime is nobody's.

Writes reference/dossiers/PACKAGES.md (client.dll: PACKAGES-client.md, packages c1..cN; its
incremental-link thunks are left out).
Usage: scripts/packages.py [N] [--lib client]   (default 9)
"""
import collections, os, re, sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))


def load(p):
    return [l.split("\t") for l in open(p).read().split("\n")[1:] if l]


def main():
    argv = sys.argv[1:]
    lib = "rc2"
    if "--lib" in argv:
        i = argv.index("--lib")
        lib = argv[i + 1]
        del argv[i:i + 2]
    n = int(argv[0]) if argv else 9
    prefix = "c" if lib == "client" else "p"
    ref = os.path.join(ROOT, "reference")
    sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
    from pe import PE
    pe = PE(os.path.join(ref, "%s.dll" % lib))
    matched = {int(r[0], 16) for r in load(os.path.join(ref, "names-%s.tsv" % lib))}
    order, work = [], collections.OrderedDict()
    for rva, size, name, fl in load(os.path.join(ref, "files-%s.tsv" % lib)):
        if fl.startswith("libcmt") or (fl.startswith("new: libcmt:") and (" .. libcmt:" in fl or fl.endswith(" .. end"))):
            continue
        if lib == "client" and int(size) == 5 and pe.read(int(rva, 16), 1) == b"\xe9":
            continue
        if fl not in work:
            work[fl] = {"bytes": 0, "fns": 0, "classes": collections.Counter(), "first": int(rva, 16), "last": 0}
        w = work[fl]
        w["last"] = int(rva, 16) + int(size)
        if int(rva, 16) not in matched:
            w["bytes"] += int(size)
            w["fns"] += 1
            m = re.match(r"([A-Za-z_]\w*)::", name)
            if m:
                w["classes"][m.group(1)] += 1
    total = sum(w["bytes"] for w in work.values())
    target = total / n
    packages, cur, acc = [], [], 0
    for fl, w in work.items():
        cur.append(fl)
        acc += w["bytes"]
        if acc >= target and len(packages) < n - 1:
            packages.append(cur)
            cur, acc = [], 0
    if cur:
        packages.append(cur)

    out = os.path.join(ref, "dossiers", "PACKAGES.md" if lib == "rc2" else "PACKAGES-%s.md" % lib)
    with open(out, "w") as f:
        head = ("# %s.dll work packages\n\nGenerated by `scripts/packages.py %d%s`; don't edit by hand. "
                % (lib, n, "" if lib == "rc2" else " --lib " + lib))
        head += ("Each package is a contiguous stretch of the original's .text: its SDK 2.3 files (the "
                 "functions RC2 changed in them) and the runs of RC2's own code between them "
                 "(`new: <after> .. <before>`, files of our naming in `%s`). `scripts/check_coverage.py %s"
                 "<file label> --missing` lists a file's functions.\n\n"
                 % ("dlls/rc2/" if lib == "rc2" else "cl_dll/rc2/", "" if lib == "rc2" else "--lib " + lib + " "))
        f.write(head)
        f.write("```\npackage  RC2 code   functions  .text range\n")
        for i, fs in enumerate(packages):
            b = sum(work[x]["bytes"] for x in fs)
            c = sum(work[x]["fns"] for x in fs)
            f.write("%s%d       %6d B  %5d      0x%x-0x%x\n" % (prefix, i + 1, b, c, work[fs[0]]["first"], work[fs[-1]]["last"]))
        f.write("total    %6d B\n```\n" % total)
        for i, fs in enumerate(packages):
            f.write("\n## %s%d\n\n```\n" % (prefix, i + 1))
            for x in fs:
                w = work[x]
                if not w["fns"]:
                    continue
                cls = " ".join(c for c, _ in w["classes"].most_common(6))
                f.write("%-46s %4d fns %7d B  %s\n" % (x, w["fns"], w["bytes"], cls))
            f.write("```\n")
    print("%d packages of about %d bytes -> %s" % (len(packages), target, os.path.relpath(out, ROOT)))


if __name__ == "__main__":
    main()
