#!/usr/bin/env python3
"""inventory.py - the reconstruction work list for an RC2 library.

From reference/files-<lib>.tsv (scripts/files.py: each function's source file by link order)
and the name tables. A function is "matched" when it has a name from the VC6 reference build
(byte for byte, or its stock vtable slot); everything else is RC2's code, either in a run no
SDK 2.3 file explains (RC2's own files, or changed stock code at a file's edge) or inside an
SDK file (a stock function RC2 changed, or one the matcher skipped as ambiguous). Classes come
from Ghidra's names (namespaces) and RC2's exported methods.

Writes reference/RECONSTRUCTION-<lib>.md.
Usage: scripts/inventory.py rc2
"""
import collections, os, re, sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from pe import PE

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))


def load(path):
    return [l.split("\t") for l in open(path).read().split("\n")[1:] if l]


def main():
    lib = sys.argv[1] if len(sys.argv) > 1 else "rc2"
    ref = os.path.join(ROOT, "reference")
    matched = set()
    for suffix in (".tsv", "-slots.tsv"):
        p = os.path.join(ref, "names-%s%s" % (lib, suffix))
        if os.path.exists(p):
            matched |= {int(r[0], 16) for r in load(p)}
    pe = PE(os.path.join(ref, "%s.dll" % lib))
    exported = {r: n for n, r in pe.exports().items()}
    rows = load(os.path.join(ref, "files-%s.tsv" % lib))

    files = collections.OrderedDict()
    for rva, size, name, fl in rows:
        rva, size = int(rva, 16), int(size)
        if fl.startswith("libcmt"):
            fl = "(C runtime)"
        e = files.setdefault(fl, {"fns": 0, "bytes": 0, "rc2": 0, "rc2_bytes": 0, "classes": collections.Counter(), "first": rva})
        e["fns"] += 1
        e["bytes"] += size
        if rva not in matched and fl != "(C runtime)":
            e["rc2"] += 1
            e["rc2_bytes"] += size
        m = re.match(r"([A-Za-z_]\w*)::", name)
        if m and rva not in matched:
            e["classes"][m.group(1)] += 1
        en = exported.get(rva, "")
        m = re.match(r"\?[^@]+@([^@]+)@@", en)
        if m:
            e["classes"][m.group(1)] += 1

    own = [(k, v) for k, v in files.items() if k.startswith("new")]
    sdk = [(k, v) for k, v in files.items() if not k.startswith("new") and k != "(C runtime)"]
    crt = files.get("(C runtime)", {"fns": 0, "bytes": 0})
    tot_f = sum(v["fns"] for _, v in files.items())
    tot_b = sum(v["bytes"] for _, v in files.items())
    own_f, own_b = sum(v["fns"] for _, v in own), sum(v["bytes"] for _, v in own)
    sdk_f, sdk_b = sum(v["fns"] for _, v in sdk), sum(v["bytes"] for _, v in sdk)
    ch_f, ch_b = sum(v["rc2"] for _, v in sdk), sum(v["rc2_bytes"] for _, v in sdk)

    out = os.path.join(ref, "RECONSTRUCTION-%s.md" % lib)
    w = open(out, "w")
    w.write("# Rocket Crowbar 2 %s: reconstruction work list\n\n" % ("server (rc2.dll)" if lib == "rc2" else "client (client.dll)"))
    w.write("Generated by `scripts/inventory.py` from `reference/files-%s.tsv`; don't edit by hand. "
            "\"Matched\" means named from the VC6 SDK 2.3 build, byte for byte or by stock vtable slot, "
            "and needs nothing beyond SDK 2.3's own code. Everything else is RC2's to reconstruct. "
            "Files are found by link order (`scripts/files.py`), so a run between two SDK files can "
            "be RC2's own file or a changed function at an SDK file's edge.\n\n" % lib)
    w.write("## Totals\n\n```\n")
    w.write("functions                               %5d  %8d bytes\n" % (tot_f, tot_b))
    w.write("  C runtime                             %5d  %8d bytes\n" % (crt["fns"], crt["bytes"]))
    w.write("  in runs no SDK file explains (%3d)    %5d  %8d bytes\n" % (len(own), own_f, own_b))
    w.write("  in SDK 2.3 files (%3d)                %5d  %8d bytes\n" % (len(sdk), sdk_f, sdk_b))
    w.write("    not matched (changed or ambiguous)  %5d  %8d bytes\n" % (ch_f, ch_b))
    w.write("```\n\n")
    w.write("## RC2's own code, in .text order\n\nBetween which SDK files each run sits, then the classes "
            "its functions and exported methods name.\n\n```\n")
    for k, v in sorted(own, key=lambda kv: kv[1]["first"]):
        if v["bytes"] < 300 and not v["classes"]:
            continue
        cls = " ".join(c for c, _ in v["classes"].most_common(8))
        w.write("%-44s %4d fns %7d B  %s\n" % (k[5:], v["fns"], v["bytes"], cls))
    small = [v for k, v in own if v["bytes"] < 300 and not v["classes"]]
    w.write("```\n\n%d more runs under 300 bytes with no class (%d functions, %d bytes) are left out; "
            "most are a file's static initializers.\n\n" % (len(small), sum(v["fns"] for v in small),
                                                            sum(v["bytes"] for v in small)))
    w.write("## SDK 2.3 files, by RC2 code inside them\n\n```\n")
    w.write("%-30s %5s %8s %10s\n" % ("file", "fns", "bytes", "not matched"))
    for k, v in sorted(sdk, key=lambda kv: -kv[1]["rc2_bytes"]):
        w.write("%-30s %5d %8d %5d %7d B  %s\n" % (k, v["fns"], v["bytes"], v["rc2"], v["rc2_bytes"],
                                                  " ".join(c for c, _ in v["classes"].most_common(5))))
    w.write("```\n")
    w.close()
    print("%s -> %s" % (lib, os.path.relpath(out, ROOT)))


if __name__ == "__main__":
    main()
