#!/usr/bin/env python3
"""gen_prefs.py - generate the rc2.ini key table source from reference/prefs-rc2.tsv.

RC2 describes every rc2.ini key in one static table (scripts/prefs.py reads it out of
rc2.dll). This writes that table as source, in the original's order and record layout:

  dlls/rc2prefs_table.h    enum rc2pref_e: RC2P_<Heading>_<Key> = the record's index
  dlls/rc2prefs_table.cpp  g_rc2Prefs[]: { type, heading, key, default, flags } per key

The record and value types are in dlls/rc2prefs.h (hand-written). Don't edit the two
generated files; rerun this.
Usage: scripts/gen_prefs.py [--check]
"""
import os, sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))

HEADER = """//========= Generated by scripts/gen_prefs.py from reference/prefs-rc2.tsv; don't edit. =========
//
// Rocket Crowbar 2: the index of every rc2.ini key in g_rc2Prefs (rc2prefs_table.cpp), in
// the original's table order. Names are RC2P_<heading>_<key>, from the table's own strings.
"""


def rows():
    out = []
    for line in open(os.path.join(ROOT, "reference", "prefs-rc2.tsv")).read().split("\n")[1:]:
        if line:
            i, value, t, h, k, d, fl = line.split("\t")
            out.append((int(i), value, t, h, k, d, int(fl, 16)))
    return out


def raw_types():
    """The table's own type codes (the tsv folds 0/1 to float and 4/5 to short)."""
    sys.path.insert(0, os.path.join(ROOT, "scripts"))
    import struct
    from pe import PE
    import prefs
    pe = PE(os.path.join(ROOT, "reference", "rc2.dll"))
    n = (prefs.VALUES_END - prefs.VALUES) // 8
    return [struct.unpack_from("<i", pe.read(prefs.RECORDS - pe.base + i * prefs.SIZE, 4), 0)[0] for i in range(n)]


def cstr(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def render():
    rs = rows()
    types = raw_types()
    h = [HEADER, "#pragma once\n\nenum rc2pref_e\n{\n"]
    for i, _, _, head, key, _, _ in rs:
        h.append("\tRC2P_%s_%s = %d,\n" % (head, key, i))
    h.append("\n\tRC2P_COUNT = %d\n};\n" % len(rs))
    c = [HEADER.replace("the index of every rc2.ini key in g_rc2Prefs (rc2prefs_table.cpp)",
                        "the rc2.ini key table (orig .data 0x1014e568, 168-byte records)"),
         '\n#include "rc2prefs.h"\n\n',
         "// { type, heading, key, default, flags }; the values are g_rc2PrefValues (rc2prefs.cpp)\n",
         "const rc2pref_t g_rc2Prefs[RC2P_COUNT] = {\n"]
    for (i, _, _, head, key, d, fl), t in zip(rs, types):
        c.append("\t{%d, %s, %s, %s, 0x%x}, // %d\n" % (t, cstr(head), cstr(key), cstr(d), fl, i))
    c.append("};\n")
    return "".join(h), "".join(c)


def main():
    h, c = render()
    paths = [os.path.join(ROOT, "dlls", "rc2prefs_table.h"), os.path.join(ROOT, "dlls", "rc2prefs_table.cpp")]
    if "--check" in sys.argv:
        stale = [p for p, t in zip(paths, (h, c)) if not os.path.exists(p) or open(p).read() != t]
        if stale:
            sys.exit("stale: " + " ".join(os.path.relpath(p, ROOT) for p in stale) + " (run scripts/gen_prefs.py)")
        return
    for p, t in zip(paths, (h, c)):
        open(p, "w").write(t)
    print("%d keys -> dlls/rc2prefs_table.h, dlls/rc2prefs_table.cpp" % len(rows()))


if __name__ == "__main__":
    main()
